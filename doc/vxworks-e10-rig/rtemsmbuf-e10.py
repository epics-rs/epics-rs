# rtemsmbuf-e10.py — find the libbsd mbuf-cluster ceiling on armv7-rtems, and
# find out what the IOC does when it is reached.
#
# Why this is a separate arena from everything already measured: the IOC's heap
# query (`RTEMS:MEM_FREE` / `MEM_BLK`, i.e. `_Protected_heap_Get_information`
# over `RTEMS_Malloc_Heap`, i.e. `malloc_free_space()`) cannot see mbuf clusters
# at all.  libbsd takes its packet memory from its own allocator domain, sized
# by `RTEMS_BSD_ALLOCATOR_DOMAIN_PAGE_MBUF_DEFAULT` = 8 MiB
# (`rtemsbsd/include/rtems/bsd/bsd.h:59`), and `kern_mbuf.c:146` then sets
#
#     nmbclusters = maxmbufmem / MCLBYTES / 4 = 8388608 / 2048 / 4 = 1024
#
# `crates/epics-rtems-boot/csrc/rtems_init.c:264` calls `rtems_bsd_initialize()`
# without touching `rtems_bsd_allocator_domain_page_mbuf_size`, so the default
# stands.  1024 clusters is the whole packet budget for the target; this arm is
# the behavioural check on that number and on what happens at it.
#
# Method.  Every load client subscribes and then never reads its socket, so the
# server's writes back up into that socket's send buffer, which is where the
# clusters go.  The events are generated by a client this script controls — a
# dedicated writer looping CA_PROTO_WRITE on a passive PV — rather than by the
# guest's own 5 Hz tick task, because that task runs at `ThreadPriority::Low`
# and stops being scheduled under exactly this load.
#
# The ceiling is then found by threshold search on the client count across fresh
# boots: `[zone: mbuf_cluster] kern.ipc.nmbclusters limit reached` on the guest
# console is the marker.  Liveness afterwards is what decides whether this is a
# third budgeted resource or a new defect.
