    /// Each module's structs and modules, its type namespace, hold each
    /// name once.
    fn assert_type_names_unique(items: &[Item]) {
        let mut seen = std::collections::HashSet::new();
        for item in items {
            let name = match item {
                Item::Struct(s) => &s.name,
                Item::Mod(name, inner) => {
                    assert_type_names_unique(inner);
                    name
                }
                _ => continue,
            };
            assert!(seen.insert(name), "{name} is declared twice");
        }
    }

