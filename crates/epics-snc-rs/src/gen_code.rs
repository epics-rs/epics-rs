//! Code generation (C `gen_code.c`): the Rust module a program compiles
//! to, built as a [`rust_out`] tree. The functions of the state sets come
//! from `gen_ss_code`, the tables from `gen_tables`.
//!
//! Escaped C is bound to its companion arm by a key, built here for both
//! item and statement position ([`escaped_key`], [`escaped_lit`]).

use std::path::Path;

use crate::driver::{Exit, Snc};
use crate::gen_ss_code::{gen_funcdef, gen_ss_code};
use crate::gen_tables::gen_tables;
use crate::rust_out::{self, Expr, Field, Fn, Item, Stmt, Struct};
use crate::seq_prim_types::PrimType;
