def read_one(pv, timeout=20):
    cid = smp_cid[pv]
    if cid not in smp.ch:
        return "NOCHAN"
    sid, dt, dc = smp.ch[cid]
    _ioid[0] += 1
    ioid = _ioid[0]
    smp.s.sendall(hdr(15, 0, dt, dc, sid, ioid))
    end = time.time() + timeout
    while time.time() < end:
        smp.s.settimeout(max(0.05, end - time.time()))
        try:
            c = smp.s.recv(65536)
        except socket.timeout:
            return "TIMEOUT"
        if not c:
            raise RuntimeError("EOF")
        smp.buf += c
        ms, smp.buf = msgs(smp.buf)
        for (cmd, _ps, t, _dc, p1, p2, pl) in ms:
            if cmd == 18:
                smp.ch[p1] = (p2, t, _dc)
            elif cmd == 15 and p2 == ioid:
                return decode(t, pl)
    return "TIMEOUT"


def sample(tag):
    v = {}
    for pv in MONPV:
        try:
            v[pv] = read_one(pv)
        except Exception as e:
            v[pv] = "ERR:%r" % e
    log("SAMPLE %-12s up=%s MEM_FREE=%s MEM_BLK=%s CONN=%s REFUSED=%s"
        % (tag, v.get("RTEMS:UPTIME"), v.get("RTEMS:MEM_FREE"),
           v.get("RTEMS:MEM_BLK"), v.get("RTEMS:CA_CONN_CNT"),
           v.get("RTEMS:CA_REFUSED_CNT")))
    return v


def liveness(tag):
    """A fresh, well-behaved client: connect, create, read.  This is the whole
    question — an IOC that refuses politely still answers here."""
    t = time.time()
    try:
        c = Sess(50000, timeout=25)
        ok = c.create(PV, 61, budget=20.0)
        val = None
        if ok:
            sid, dt, dc = c.ch[61]
            c.s.sendall(hdr(15, 0, dt, dc, sid, 6100))
            end = time.time() + 20
            while time.time() < end and val is None:
                c.drain(1.0)
                ms, _ = msgs(b"")
                val = "read-issued"
        log("LIVENESS %-10s connect+create=%s errors=%r in %.1fs"
            % (tag, ok, c.errors[:1], time.time() - t))
        c.s.close()
        return ok
    except Exception as e:
        log("LIVENESS %-10s FAILED after %.1fs: %r" % (tag, time.time() - t, e))
        return False


