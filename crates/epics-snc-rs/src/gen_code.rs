const NM_VARS: &str = "seqg_vars";
const NM_STATIC_VARS: &str = "seqg_static_vars";

/// C `generate_code`: the program's Rust, written to the output.
pub fn generate_code(snc: &mut Snc, ast: &Ast, prg: &Program) -> Result<(), Exit> {
    let prog = &ast[prg.prog];
    let name = prg.name.as_deref().unwrap_or_default();

    let mut body = vec![
        Item::Attr(
            "#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, clippy::all)]"
                .into(),
        ),
        Item::Blank,
        Item::Use {
            public: false,
            path: "super::*".into(),
        },
        Item::Use {
            public: false,
            path: "epics_seq_rs as seqg_rt".into(),
        },
    ];

    // definitions except variables, in program order, escaped C included
    let defns = gen_global_defns(snc, ast, prg, prog.child(child::PROG_DEFNS));
    section(&mut body, defns);
    let vars = gen_var_struct(snc, ast, prg);
    section(&mut body, vars);
    // gen_func_decls: Rust needs no function declarations
    let ss_code = gen_ss_code(snc, ast, prg)?;
    section(&mut body, ss_code);
    let tables = gen_tables(snc, ast, prg);
    section(&mut body, tables);
    let xdefns = gen_global_defns(snc, ast, prg, prog.child(child::PROG_XDEFNS));
    section(&mut body, xdefns);

    if prg.options.main {
        // seqMain.c's main() belongs to the crate, not to the program
        snc.error_at_node(
            prog,
            format_args!("snc-rs cannot generate a main program (option +m)\n"),
        );
    }
    section(&mut body, gen_init_reg(name));

    let items = [
        Item::Comment(format!(
            "Rust code for program {name}, generated by snc-rs from {}.",
            file_name(prog)
        )),
        Item::Blank,
        Item::Mod("seqg".into(), body),
        Item::Blank,
        Item::Use {
            public: true,
            path: format!("seqg::{{{name}, {name}Registrar}}"),
        },
    ];
    snc.gen_code(format_args!("{}", rust_out::print(&items)));
    Ok(())
}

/// C `gen_init_reg`: the program's registrar.
fn gen_init_reg(prog_name: &str) -> Vec<Item> {
    vec![
        Item::Comment("Register sequencer commands and program".into()),
        Item::Fn(Fn {
            public: true,
            name: format!("{prog_name}Registrar"),
            params: Vec::new(),
            ret: None,
            body: vec![
                Stmt::Expr(Expr::call(
                    "seqg_rt::seq_register_sequencer_commands",
                    Vec::new(),
                )),
                Stmt::Expr(Expr::call(
                    "seqg_rt::seq_register_sequencer_program",
                    vec![Expr::unary("&", Expr::atom(prog_name))],
                )),
            ],
        }),
    ]
}

/// `items` after an empty line, unless there are none.
fn section(out: &mut Vec<Item>, items: Vec<Item>) {
    if !items.is_empty() {
        out.push(Item::Blank);
        out.extend(items);
    }
}

/// The base name of the file `ep` came from: build scripts compile by
/// absolute path, and the generated text must not depend on it.
fn file_name(ep: &Node) -> &str {
    let file = ep.token.file.as_deref().unwrap_or("(null)");
    Path::new(file)
        .file_name()
        .and_then(|f| f.to_str())
        .unwrap_or(file)
}

/// C `gen_line_marker`: the `<file>:<line>` comment before the code of
/// `ep`, unless line markers are off (`-l`).
pub fn line_comment(snc: &Snc, ep: &Node) -> Option<String> {
    snc.options
        .line
        .then(|| format!("{}:{}", file_name(ep), ep.token.line))
}

fn push_line_comment(out: &mut Vec<Item>, snc: &Snc, ep: &Node) {
    out.extend(line_comment(snc, ep).map(Item::Comment));
}

pub(crate) fn vars(ast: &Ast, list: Option<VarListId>) -> impl Iterator<Item = VarId> + '_ {
    std::iter::successors(list.and_then(|l| ast[l].first), |&vp| ast[vp].next)
}

/// The `seqg_rt` type of a `typename` that seq's run time defines,
/// `pvAlarm.h`'s enums.
pub(crate) fn rt_typename(name: &str) -> Option<&'static str> {
    match name {
        "pvStat" => Some("PvStat"),
        "pvSevr" => Some("PvSevr"),
        _ => None,
    }
}

/// The Rust type of a value of SNL type `t`, or the part of `t` that has
/// none.
pub(crate) fn value_type(ast: &Ast, t: crate::types::TypeId) -> Result<String, String> {
    Ok(match &ast[t].kind {
        TypeKind::Prim(p) => match p {
            PrimType::Char => "std::ffi::c_char",
            PrimType::UChar | PrimType::UInt8T => "u8",
            PrimType::Short | PrimType::Int16T => "i16",
            PrimType::UShort | PrimType::UInt16T => "u16",
            PrimType::Int | PrimType::Int32T => "i32",
            PrimType::UInt | PrimType::UInt32T => "u32",
            PrimType::Long => "i64",
            PrimType::ULong => "u64",
            PrimType::Int8T => "i8",
            PrimType::Float => "f32",
            PrimType::Double => "f64",
            PrimType::String => "seqg_rt::SeqString",
        }
        .to_owned(),
        TypeKind::Pointer { value_type: t } => match &ast[*t].kind {
            TypeKind::Prim(PrimType::Char) => "seqg_rt::CharPtr".to_owned(),
            TypeKind::Void => "seqg_rt::Ptr<std::ffi::c_void>".to_owned(),
            TypeKind::Function { .. } => return Err("function pointer".into()),
            _ => format!(
                "seqg_rt::Ptr<{}>",
                value_type(ast, *t).map_err(|e| format!("pointer to {e}"))?
            ),
        },
        TypeKind::Array {
            num_elems,
            elem_type,
        } => format!("[{}; {num_elems}]", value_type(ast, *elem_type)?),
        TypeKind::Foreign {
            tag: ForeignTag::Typename,
            name,
        } => match rt_typename(name) {
            Some(r) => format!("seqg_rt::{r}"),
            None => return Err(format!("typename {name}")),
        },
        TypeKind::Foreign { tag, name } => return Err(format!("{}{name}", tag.prefix())),
        TypeKind::Struct { name, .. } => return Err(format!("struct {name}")),
        k => return Err(k.tag_name().into()),
    })
}

/// C `gen_var_decl`: the type variable `vp` is declared with, e.g.
/// `seqg_rt::SeqVar<i32>` or `[seqg_rt::SeqVar<f64>; 4]`. A type snc-rs
/// refuses is reported at the declaration.
pub fn gen_var_decl(snc: &mut Snc, ast: &Ast, vp: VarId) -> String {
    let var = &ast[vp];
    let ty = match (&ast[var.type_].kind, var.assign) {
        // a multi-PV array is one variable per channel
        (
            TypeKind::Array {
                num_elems,
                elem_type,
            },
            Multiplicity::Multi,
        ) => value_type(ast, *elem_type).map(|t| format!("[seqg_rt::SeqVar<{t}>; {num_elems}]")),
        _ => value_type(ast, var.type_).map(|t| format!("seqg_rt::SeqVar<{t}>")),
    };
    ty.unwrap_or_else(|unsupported| {
        let decl = var.decl.expect("generated variables are declared");
        snc.error_at_node(
            &ast[decl],
            format_args!(
                "snc-rs does not support {unsupported} variable '{}'\n",
                var.name.as_deref().unwrap_or_default()
            ),
        );
        "()".into()
    })
}

/// C `gen_defn_c_code`: the escaped C among the definitions of `scope`,
/// each a `seqg_escaped!(r#"..."#);` item after its `// file:line`
/// comment. In a block body each item is a [`crate::rust_out::Stmt::Item`].
pub fn gen_defn_c_code(snc: &mut Snc, ast: &Ast, scope: NodeId) -> Vec<Item> {
    let texts: Vec<NodeId> = ast
        .list(ast.defn_list_from_scope(scope))
        .filter(|&ep| ast[ep].tag == NodeTag::TText)
        .collect();
    let mut out = Vec::new();
    if !texts.is_empty() {
        out.push(Item::Comment("C code definitions".into()));
        gen_escaped_items(&mut out, snc, ast, &texts);
    }
    out
}

/// Item-position escaped C: each run of fragments whose brackets balance
/// only together is one call, as at statement position.
fn gen_escaped_items(out: &mut Vec<Item>, snc: &Snc, ast: &Ast, texts: &[NodeId]) {
    let mut i = 0;
    while i < texts.len() {
        push_line_comment(out, snc, &ast[texts[i]]);
        let mut args = Vec::new();
        let mut balance = 0;
        loop {
            let text = ast[texts[i]].token.text();
            balance += c_bracket_balance(text);
            args.push(escaped_lit(&escaped_key(text)).into());
            i += 1;
            if balance == 0 || i == texts.len() {
                break;
            }
        }
        out.push(Item::Expr(Expr::Macro("seqg_escaped".into(), args)));
    }
}

/// C `gen_global_defn` over the list starting at `first`.
fn gen_global_defns(snc: &mut Snc, ast: &Ast, prg: &Program, first: Option<NodeId>) -> Vec<Item> {
    let mut out = Vec::new();
    let defns: Vec<NodeId> = ast.list(first).collect();
    let mut i = 0;
    while i < defns.len() {
        let ep = &ast[defns[i]];
        match ep.tag {
            NodeTag::TText => {
                let run = defns[i..]
                    .iter()
                    .take_while(|&&d| ast[d].tag == NodeTag::TText)
                    .count();
                gen_escaped_items(&mut out, snc, ast, &defns[i..i + run]);
                i += run;
                continue;
            }
            NodeTag::DFuncdef => out.extend(gen_funcdef(snc, ast, prg, defns[i])),
            NodeTag::DStructdef => snc.error_at_node(
                ep,
                format_args!("snc-rs does not support struct definitions\n"),
            ),
            NodeTag::DDecl => {
                // only event flags here, everything else is in gen_var_struct
                let vp = ep.e_decl().expect("declaration without variable");
                if let VarChan::EvFlag(ef) = &ast[vp].chan {
                    let var = &ast[vp];
                    push_line_comment(&mut out, snc, &ast[var.decl.expect("declared")]);
                    out.push(Item::Const(rust_out::Const {
                        public: false,
                        is_static: false,
                        name: var.name.as_deref().unwrap_or_default().into(),
                        ty: "seqg_rt::EfId".into(),
                        expr: Expr::call("seqg_rt::EfId", vec![Expr::Atom(ef.index.to_string())]),
                    }));
                }
            }
            // no direct correspondence to a declaration
            NodeTag::DAssign
            | NodeTag::DMonitor
            | NodeTag::DOption
            | NodeTag::DSync
            | NodeTag::DSyncq => {}
            tag => unreachable!("global defn {}", tag.name()),
        }
        i += 1;
    }
    out
}

/// One field per variable of `list`, each after its line comment.
fn var_fields(snc: &mut Snc, ast: &Ast, list: impl Iterator<Item = VarId>) -> Vec<Field> {
    list.map(|vp| {
        let var = &ast[vp];
        let decl = &ast[var.decl.expect("generated variables are declared")];
        Field {
            comments: line_comment(snc, decl).into_iter().collect(),
            public: true,
            name: var.name.as_deref().unwrap_or_default().into(),
            ty: gen_var_decl(snc, ast, vp),
        }
    })
    .collect()
}

/// A struct of variables and the impl that zeroes it.
fn var_struct(out: &mut Vec<Item>, name: String, fields: Vec<Field>, zeroed_impl: &str) {
    let zeroed = Expr::Struct(
        name.clone(),
        fields
            .iter()
            .map(|f| {
                (
                    f.name.clone(),
                    Expr::call("seqg_rt::Zeroed::zeroed", Vec::new()),
                )
            })
            .collect(),
    );
    out.push(Item::Attr("#[derive(Clone)]".into()));
    out.push(Item::Struct(Struct {
        public: true,
        name: name.clone(),
        fields,
    }));
    out.push(Item::Blank);
    out.push(Item::Impl(
        format!("impl {zeroed_impl} for {name}"),
        vec![Item::Fn(Fn {
            public: false,
            name: "zeroed".into(),
            params: Vec::new(),
            ret: Some("Self".into()),
            body: vec![Stmt::Tail(zeroed)],
        })],
    ));
}

/// C `gen_var_struct`: the variables with program lifetime, those of the
/// top level, of each state set and of each state. Rust cannot nest the
/// struct definitions as C does, so a state set's struct and its states'
/// are module `seqg_vars_<ss>`'s `seqg_vars` and `seqg_vars_<state>`: each
/// type name is built from one SNL name, unique in its scope, so no two
/// can collide however the names are spelled.
fn gen_var_struct(snc: &mut Snc, ast: &Ast, prg: &Program) -> Vec<Item> {
    let prog = &ast[prg.prog];
    let mut out = vec![Item::Comment("Variable declarations".into())];
    let globals = vars(ast, Some(ast.var_list_from_scope(prg.prog))).filter(|&vp| {
        let var = &ast[vp];
        var.decl.is_some()
            && !matches!(
                ast[var.type_].kind,
                TypeKind::None | TypeKind::EvFlag | TypeKind::Function { .. }
            )
    });
    let mut fields = var_fields(snc, ast, globals);
    let mut ss_mods = Vec::new();
    for ssp in ast.list(prog.child(child::PROG_STATESETS)) {
        let ss = &ast[ssp];
        let ss_name = ss.token.text();
        let states: Vec<NodeId> = ast.list(ss.child(child::SS_STATES)).collect();
        let ss_vars = ast.var_list_from_scope(ssp);
        let ss_empty = ast[ss_vars].first.is_none()
            && states
                .iter()
                .all(|&sp| ast[ast.var_list_from_scope(sp)].first.is_none());
        if ss_empty {
            continue;
        }
        let ss_mod = format!("{NM_VARS}_{ss_name}");
        let mut ss_fields = var_fields(snc, ast, vars(ast, Some(ss_vars)));
        let mut state_structs = Vec::new();
        for &sp in &states {
            let state_vars = ast.var_list_from_scope(sp);
            if ast[state_vars].first.is_none() {
                continue;
            }
            let state_name = ast[sp].token.text();
            let state_struct = format!("{NM_VARS}_{state_name}");
            ss_fields.push(Field {
                comments: Vec::new(),
                public: true,
                name: state_struct.clone(),
                ty: state_struct.clone(),
            });
            let state_fields = var_fields(snc, ast, vars(ast, Some(state_vars)));
            state_structs.push((state_struct, state_fields));
        }
        fields.push(Field {
            comments: Vec::new(),
            public: true,
            name: ss_mod.clone(),
            ty: format!("{ss_mod}::{NM_VARS}"),
        });
        let mut items = vec![
            Item::Use {
                public: false,
                path: "super::*".into(),
            },
            Item::Blank,
        ];
        var_struct(&mut items, NM_VARS.into(), ss_fields, "seqg_rt::Zeroed");
        for (name, fields) in state_structs {
            items.push(Item::Blank);
            var_struct(&mut items, name, fields, "seqg_rt::Zeroed");
        }
        ss_mods.push(Item::Mod(ss_mod, items));
    }
    var_struct(&mut out, NM_VARS.into(), fields, "seqg_rt::ProgramVars");
    for ss_mod in ss_mods {
        out.push(Item::Blank);
        out.push(ss_mod);
    }
    if !prg.options.reent {
        out.push(Item::Blank);
        out.extend(gen_static_vars());
    }
    out
}

/// `-r`: the one variable block every start shares, as C's statics.
fn gen_static_vars() -> Vec<Item> {
    let block = rust_out::Const {
        public: false,
        is_static: true,
        name: "seqg_static".into(),
        ty: format!("std::sync::LazyLock<{NM_VARS}>"),
        expr: Expr::call(
            "std::sync::LazyLock::new",
            vec![Expr::atom(format!(
                "<{NM_VARS} as seqg_rt::ProgramVars>::zeroed"
            ))],
        ),
    };
    vec![
        Item::Comment("Variable block of the program (-r)".into()),
        Item::Fn(Fn {
            public: true,
            name: NM_STATIC_VARS.into(),
            params: Vec::new(),
            ret: Some(format!("&'static {NM_VARS}")),
            body: vec![
                Stmt::Item(Item::Const(block)),
                Stmt::Tail(Expr::unary("&", Expr::atom("seqg_static"))),
            ],
        }),
    ]
}

/// How a C text scanner sees one byte.
#[derive(Clone, Copy, PartialEq)]
pub(crate) enum CClass {
    Code,
    /// inside a string or character literal, quotes included
    Literal,
    /// inside a `/* */` comment, delimiters included
    Comment,
    /// inside a `//` comment, up to its newline
    LineComment,
}

/// Classify each byte of C text, as cpp would tokenise it.
pub(crate) fn c_classes(text: &[u8]) -> Vec<CClass> {
    let mut out = vec![CClass::Code; text.len()];
    let mut i = 0;
    while i < text.len() {
        let start = i;
        let class = match text[i] {
            q @ (b'"' | b'\'') => {
                i += 1;
                while i < text.len() && text[i] != q && text[i] != b'\n' {
                    i += if text[i] == b'\\' { 2 } else { 1 };
                }
                i = (i + 1).min(text.len());
                CClass::Literal
            }
            b'/' if text.get(i + 1) == Some(&b'*') => {
                i = match text[i + 2..].windows(2).position(|w| w == b"*/") {
                    Some(p) => i + 2 + p + 2,
                    None => text.len(),
                };
                CClass::Comment
            }
            b'/' if text.get(i + 1) == Some(&b'/') => {
                while i < text.len() && text[i] != b'\n' {
                    i += 1;
                }
                CClass::LineComment
            }
            _ => {
                i += 1;
                continue;
            }
        };
        out[start..i].fill(class);
    }
    out
}

/// The binding key of an escaped C fragment: cpp line-marker lines
/// (`^#\s*\d+\s+"`) removed, each run of whitespace outside literals and
/// comments made one space, or one newline after a `//` comment, so that
/// code after the comment does not read as comment text; the ends trimmed.
pub fn escaped_key(text: &str) -> String {
    let mut kept = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        if !is_line_marker(line) {
            kept.push_str(line);
        }
    }
    let bytes = kept.as_bytes();
    let classes = c_classes(bytes);
    let mut key = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if classes[i] == CClass::Code && bytes[i].is_ascii_whitespace() {
            let start = i;
            while i < bytes.len() && classes[i] == CClass::Code && bytes[i].is_ascii_whitespace() {
                i += 1;
            }
            if start > 0 && i < bytes.len() {
                key.push(match classes[start - 1] {
                    CClass::LineComment => b'\n',
                    _ => b' ',
                });
            }
        } else {
            key.push(bytes[i]);
            i += 1;
        }
    }
    // only ASCII whitespace was merged, so the bytes are still UTF-8
    String::from_utf8(key).unwrap().trim_matches(' ').to_owned()
}

fn is_line_marker(line: &str) -> bool {
    let Some(rest) = line.strip_prefix('#') else {
        return false;
    };
    let rest = rest.trim_start_matches([' ', '\t']);
    let digits = rest.len() - rest.trim_start_matches(|c: char| c.is_ascii_digit()).len();
    let rest = &rest[digits..];
    let blanks = rest.len() - rest.trim_start_matches([' ', '\t']).len();
    digits > 0 && blanks > 0 && rest[blanks..].starts_with('"')
}

/// The `(`, `{`, `[` minus `)`, `}`, `]` of C text, outside literals and
/// comments.
pub fn c_bracket_balance(text: &str) -> i32 {
    let classes = c_classes(text.as_bytes());
    text.bytes()
        .zip(classes)
        .filter(|&(_, c)| c == CClass::Code)
        .map(|(b, _)| match b {
            b'(' | b'{' | b'[' => 1,
            b')' | b'}' | b']' => -1,
            _ => 0,
        })
        .sum()
}

/// `key` as a raw string literal with the fewest `#` (at least one).
pub fn escaped_lit(key: &str) -> Expr {
    let mut longest = 0;
    for (i, _) in key.match_indices('"') {
        let run = key[i + 1..].len() - key[i + 1..].trim_start_matches('#').len();
        longest = longest.max(run);
    }
    let hashes = "#".repeat(longest + 1);
    Expr::Atom(format!("r{hashes}\"{key}\"{hashes}"))
}

