T0 = time.time()


def log(m):
    print("[%7.1fs] %s %s" % (time.time() - T0, TAG, m), flush=True)


def hdr(cmd, psize, dtype, dcount, p1, p2):
    return struct.pack(">HHHHII", cmd, psize, dtype, dcount, p1, p2)


def pad(s):
    b = s.encode() + b"\0"
    return b.ljust((len(b) + 7) // 8 * 8, b"\0")


def msgs(buf):
    out = []
    while len(buf) >= 16:
        cmd, psize, dt, dc, p1, p2 = struct.unpack(">HHHHII", buf[:16])
        if len(buf) < 16 + psize:
            break
        out.append((cmd, psize, dt, dc, p1, p2, buf[16:16 + psize]))
        buf = buf[16 + psize:]
    return out, buf


def decode(dt, pl):
    if dt == 6 and len(pl) >= 8:
        return struct.unpack(">d", pl[:8])[0]
    if dt == 5 and len(pl) >= 4:
        return struct.unpack(">i", pl[:4])[0]
    if dt == 0:
        return pl.split(b"\0")[0].decode("latin1")
    return pl[:16]


class Sess:
    def __init__(self, idx, timeout=25):
        self.idx = idx
        self.s = socket.create_connection((HOST, PORT), timeout=timeout)
        self.s.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        self.buf = b""
        self.ch = {}
        self.errors = []
        self.s.sendall(hdr(0, 0, 0, 13, 0, 0))

    def drain(self, budget=0.25, until=None):
        end = time.time() + budget
        got = 0
        while True:
            if until is not None and until(self):
                break
            left = end - time.time()
            if left <= 0:
                break
            r, _, _ = select.select([self.s], [], [], min(0.05, left))
            if not r:
                continue
            c = self.s.recv(262144)
            if not c:
                raise RuntimeError("EOF")
            got += len(c)
            self.buf += c
            ms, self.buf = msgs(self.buf)
            for (cmd, _ps, dt, dc, p1, p2, pl) in ms:
                if cmd == 18:
                    self.ch[p1] = (p2, dt, dc)
                elif cmd == 11:
                    self.errors.append((p2, pl[16:].split(b"\0")[0].decode("latin1")))
        return got

    def create(self, pv, cid, budget=25.0):
        nm = pad(pv)
        self.s.sendall(hdr(18, len(nm), 0, 0, cid, 13) + nm)
        self.drain(budget, until=lambda s: cid in s.ch)
        return cid in self.ch

    def subscribe(self, cid, n):
        sid, dt, dc = self.ch[cid]
        mask = struct.pack(">fffHH", 0.0, 0.0, 0.0, 1, 0)
        self.s.sendall(b"".join(
            hdr(1, 16, dt, dc, sid, cid * 4096 + k) + mask for k in range(n)))

    def write(self, cid, value):
        sid, dt, dc = self.ch[cid]
        pl = struct.pack(">d", value)
        self.s.sendall(hdr(4, len(pl), 6, 1, sid, 0) + pl)


